"""Builds skills/sweetpea/tasks.md: which tasks have been used for which questions, and what they compare.

Run:  python dev/build_task_overview.py <path to the corpus folder with papers/*/result.json>

Reads only what the published papers state (citation, task, the compared conditions, the factors).
It does not copy any result of a re-analysis.
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

corpus = Path(sys.argv[1])
families = defaultdict(list)
for path in sorted(corpus.glob("papers/*/result.json")):
    d = json.loads(path.read_text())
    i, design = d["identification"], d["design"]
    by_type = design["factors_by_type"]
    first = d["tests"][0] if d["tests"] else None
    families[i["task_family"]].append({
        "topic": i["topic"].replace("_", " "),
        "task": i["task"],
        "who": f'{i["authors"][0].split(",")[0]}{" et al." if len(i["authors"]) > 1 else ""} ({i["year"]}), {i["journal"]}, {i["experiment"]}',
        "doi": i["doi"],
        "compared": first["label"] if first else "",
        "regular": by_type.get("regular", []), "derived": by_type.get("derived", []), "transition": by_type.get("transition", []),
    })

lines = ["# Tasks and the questions they have been used for", "",
         "An overview for suggesting a task when a user names a research question, and for seeing what a",
         "design of that kind usually compares. One entry per published experiment with open data; the list",
         "is a sample, not a survey. Generated by `dev/build_task_overview.py`; do not edit by hand.", "",
         "How to use it: find the question or a neighbouring one, read what was compared and which factors",
         "the design had, and offer the user one or two tasks with what each is good for. A factor listed",
         "under \"from the trial before\" depends on the previous trial; the design has to say what happens to it.", ""]
for family in sorted(families):
    lines += [f"## {family.replace('_', ' ').capitalize()}", ""]
    for e in families[family]:
        names = lambda xs: ", ".join(x.replace("_", " ") for x in xs) or "none"
        lines += [f"- **Question:** {e['topic']}. **Task:** {e['task']}.",
                  f"  **Compared:** {e['compared']}. **Factors:** {names(e['regular'])}; derived: {names(e['derived'])}; "
                  f"from the trial before: {names(e['transition'])}.",
                  f"  {e['who']}. doi:{e['doi']}", ""]
out = Path(__file__).resolve().parents[1] / "skills" / "sweetpea" / "tasks.md"
out.write_text("\n".join(lines))
print(len(families), "task families,", sum(len(v) for v in families.values()), "experiments ->", out)
